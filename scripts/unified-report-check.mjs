import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import ts from 'typescript';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
const dir=await fs.mkdtemp(path.join(process.cwd(),'.sites-runtime','unified-report-'));
try{
  const files=['lib/dom-extraction.ts','lib/link-analysis.ts','lib/finding-guides.ts','lib/page-metrics.ts','lib/report-tabs.ts','lib/report-export.ts','lib/audit.ts','lib/releases.ts','lib/website-scores.ts','app/website-overview.tsx','app/source-evidence.tsx','app/link-status-report.tsx','app/heading-evidence.tsx','app/page-detail.tsx','app/report-panels.tsx','app/score-gauge.tsx','app/audit-report.tsx'];
  for(const file of files){
    const raw=(await fs.readFile(file,'utf8')).replace(/(['"])(?:\.\.\/lib\/|\.\/)([\w-]+)\1/g,(_,quote,name)=>`${quote}./${name}.mjs${quote}`);
    await fs.writeFile(path.join(dir,path.basename(file).replace(/\.tsx?$/,'.mjs')),ts.transpileModule(raw,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022,jsx:ts.JsxEmit.ReactJSX}}).outputText);
  }
  const {analyze,SAMPLE}=await import(path.join(dir,'audit.mjs'));
  const {default:AuditReport,REPORT_MENU}=await import(path.join(dir,'audit-report.mjs'));
  const {PageDetail,CategoryExplanation}=await import(path.join(dir,'page-detail.mjs'));
  const report=analyze(SAMPLE,'https://example.com/');
  const {websiteScores}=await import(path.join(dir,'website-scores.mjs'));
  assert.equal(websiteScores([]).overall,null);
  const aggregate=websiteScores([{scores:{SEO:80,AEO:null,GEO:20}},{scores:{SEO:100,AEO:60,GEO:null}}]);
  assert.deepEqual(aggregate.scores.map(s=>s.score),[90,60,20]);
  assert.deepEqual(aggregate.scores.map(s=>s.count),[2,1,1]);
  assert.equal(aggregate.overall,57);
  const {WebsiteOverview}=await import(path.join(dir,'website-overview.mjs'));
  const overview=renderToStaticMarkup(React.createElement(WebsiteOverview,{pages:[{status:'completed',report},{status:'failed',report:null}],discovered:10,selected:2}));
  assert.equal((overview.match(/role="meter"/g)||[]).length,4);
  assert.match(overview,/10% audited/);
  assert.match(overview,/Based on 1 audited page · 2 selected · 10 discovered/);
  assert.equal((overview.match(/class="website-stat website-stat--/g)||[]).length,5);
  assert.doesNotMatch(overview,/website-stat--opportunity|website-stat--unavailable/);
  assert.match(overview,/Source checks that passed/);
  assert.match(overview,/Includes unmeasured checks/);
  assert.deepEqual(REPORT_MENU,['All issues','Fix first','SEO','AEO','GEO','Page details']);
  const html=renderToStaticMarkup(React.createElement(AuditReport,{report,onBack:()=>{}}));
  assert.match(html,/aria-selected="true"[^>]*>Fix first/);
  assert.match(html,/Back to website pages/);
  assert.equal((html.match(/role="tab"/g)||[]).length,6);
  assert.equal((html.match(/class="issue-total issue-total--/g)||[]).length,5);
  assert.equal((html.match(/aria-pressed="false"/g)||[]).length,5);
  assert.match(html,/Counts represent finding groups/);
  assert.doesNotMatch(html,/issue-total--opportunity|issue-total--unavailable/);
  assert.ok(html.indexOf('class="report-navigation"')<html.indexOf('class="issue-summary"'));
  assert.ok(html.indexOf('class="report-navigation"')<html.indexOf('aria-label="Search findings"'));
  assert.ok(html.indexOf('aria-label="Search findings"')<html.indexOf('id="report-section"'));
  assert.equal((html.match(/Open Fix first report in new tab/g)||[]).length,1);
  assert.doesNotMatch(html,/class="action-plan"/);
  assert.doesNotMatch(html,/class="finding-workspace"/); // findings begin collapsed
  const details=renderToStaticMarkup(React.createElement(PageDetail,{report}));
  assert.equal((details.match(/<details\b/g)||[]).length,4);
  assert.equal((details.match(/<summary>/g)||[]).length,4);
  assert.doesNotMatch(details,/<details[^>]*\bopen\b/);
  assert.match(details,/Heading inventory/);
  assert.doesNotMatch(details,/highlighted problems|Recommended level to review|Structure check passed/);
  const {HeadingEvidence}=await import(path.join(dir,'heading-evidence.mjs'));
  const headingEvidence=renderToStaticMarkup(React.createElement(HeadingEvidence,{report,findingId:'heading-order'}));
  assert.match(headingEvidence,/Recommended level to review/);
  assert.doesNotMatch(headingEvidence,/Structure check passed/);
  const allCategory=renderToStaticMarkup(React.createElement(CategoryExplanation,{report,category:'SEO',showAction:false}));
  assert.doesNotMatch(allCategory,/new tab/);
  const source=await fs.readFile('app/legacy-workspace.tsx','utf8');
  assert.match(source,/function openPageReport\(page:Report\)[^\n]+setSection\('Audit workspace'\)/);
  assert.match(source,/<div hidden=\{!!report\}><WebsiteManager/);
  console.log('PASS: unified menu order/default, collapsed findings, new-tab button placement, four collapsed Page details accordions and audit navigation wiring. Live browser interaction not validated.');
}finally{await fs.rm(dir,{recursive:true,force:true});}
